from __future__ import annotations

import argparse

from .util import artifact_path, render_path_list, write_text


def scaffold(topic: str, inputs: list[str], out_path: str) -> None:
    text = f"""# High-Level Paper Flow: {topic}
Date: {{date}} | Inputs:
{render_path_list(inputs)}

## Paper Direction
- Working title direction: ...
- Core problem: ...
- Current contribution statement: ...
- Target venue: ...
- Why now: ...
- Core tension thread: ...

## High-Level Outline
1. Introduction
   - Problem framing: ...
   - Why it matters: ...
   - Contributions to claim: ...

2. Related Work
   - Main comparison groups: ...
   - Closest prior work to cite: ...

3. Method / Approach
   - Proposed method or system: ...
   - Key mechanism: ...
   - Assumptions: ...

4. Experiments
   - Main benchmark experiments: ...
   - Baselines: ...
   - Ablations: ...
   - Stress tests: ...

5. Results
   - Main quantitative results shown: ...
   - Main figures/tables: ...
   - Key takeaways: ...

6. Discussion
   - Strengths: ...
   - Current limitations: ...
   - Claims that need more evidence: ...

## Experiment Status Map
| Planned experiment | Claim supported | Current status | Evidence file(s) | Paper section |
|---|---|---|---|---|
| ... | ... | completed / partial / missing | ... | ... |

## Results Available Now
- Table-worthy CSV outputs: ...
- Plot-worthy PDF outputs: ...
- Result summaries already supported: ...

## Missing Evidence
- Missing experiments: ...
- Missing baselines: ...
- Missing plots/tables: ...
- Missing result interpretation: ...

## Suggested Figures and Tables
- Table 1: ...
- Figure 1: ...
- Figure 2: ...

## Reviewer Input Notes
- What is already strong: ...
- What looks risky: ...
- What should be checked next by `paper-reviewer`: ...
"""
    write_text(out_path, text.replace("{date}", __import__("datetime").date.today().isoformat()))


def main() -> None:
    ap = argparse.ArgumentParser(description="Scaffold a high-level paper-flow markdown file.")
    ap.add_argument("topic", help="Topic string for title and filename.")
    ap.add_argument("--input", action="append", default=[], help="Relevant upstream artifact path (repeatable).")
    ap.add_argument("--out", default=None, help="Output markdown path.")
    args = ap.parse_args()

    out_path = args.out or artifact_path("paper", "high-level-paper", args.topic)
    scaffold(args.topic, list(args.input), out_path)
    print(f"Wrote scaffold to {out_path}")


if __name__ == "__main__":
    main()

