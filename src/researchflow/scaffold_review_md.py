from __future__ import annotations

import argparse

from .util import artifact_path, render_path_list, write_text


def scaffold(topic: str, draft: str | None, inputs: list[str], out_path: str) -> None:
    draft_path = draft or "Unknown draft"
    text = f"""# Paper Review Report: {topic}
Date: {{date}} | Draft reviewed: {draft_path}

## Review Scope
- Sections reviewed: ...
- Additional literature search performed: yes / no
- Inputs used:
{render_path_list(inputs)}

## Draft Claims Under Review
1. ...
2. ...
3. ...

## Novelty Overlap Map
| Draft claim | Closest prior work | Overlap level | Why this is a risk | Required differentiation |
|---|---|---|---|---|
| ... | ... | already done / partial / weakly differentiated / clearly differentiated | ... | ... |

## Literature Additions
- Paper 1: ...
  - Why it must be cited: ...
  - Impact on draft claims: ...

## Claim-to-Result Audit
| Draft claim | Supporting result in current draft | Support status | What is missing |
|---|---|---|---|
| ... | ... | supported / partial / unsupported / overstated | ... |

## Impact Assessment
- Target conference: ...
- Problem importance for this venue: ...
- Current result strength: ...
- Current impact rating: low impact / promising but under-evidenced / solid / high impact
- Why: ...

## Missing Experiments
1. ...
   - Why it matters: ...
   - Which claim it supports or corrects: ...
   - Minimum acceptable version: ...

## Impact-Driven Experiment Expansion
1. ...
   - Why this would increase impact: ...
   - Which venue expectation it addresses: ...
   - Which current result it strengthens: ...
   - Smallest acceptable version: ...

## Results Refinement
- Keep as is: ...
- Weaken this wording: ...
- Add this analysis: ...
- Remove or defer this claim: ...

## Reviewer Objections Likely
1. ...
2. ...
3. ...

## Priority Fix Plan
### Tier 1
- Must fix before submission: ...

### Tier 2
- Strong improvements if time allows: ...

### Tier 3
- Nice to have: ...

## Revised Positioning
- Safer novelty claim: ...
- Safer empirical claim: ...
- New discussion points to add: ...
"""
    write_text(out_path, text.replace("{date}", __import__("datetime").date.today().isoformat()))


def main() -> None:
    ap = argparse.ArgumentParser(description="Scaffold a paper-review markdown file.")
    ap.add_argument("topic", help="Topic string for title and filename.")
    ap.add_argument("--draft", default=None, help="Draft path under results/paper/.")
    ap.add_argument("--input", action="append", default=[], help="Relevant upstream artifact path (repeatable).")
    ap.add_argument("--out", default=None, help="Output markdown path.")
    args = ap.parse_args()

    out_path = args.out or artifact_path("review", "Review", args.topic)
    scaffold(args.topic, args.draft, list(args.input), out_path)
    print(f"Wrote scaffold to {out_path}")


if __name__ == "__main__":
    main()
