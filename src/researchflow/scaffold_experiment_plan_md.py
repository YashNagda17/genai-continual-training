from __future__ import annotations

import argparse

from .util import artifact_path, render_path_list, write_text


def scaffold(topic: str, venue: str | None, inputs: list[str], out_path: str) -> None:
    venue_text = venue or "Unknown"
    text = f"""# Experiment Plan: {topic}
Date: {{date}} | Target venue: {venue_text} | Inputs:
{render_path_list(inputs)}

## Final Idea Under Test
- Current claim: ...
- Domain-backed mechanism: ...
- Main reviewer risk: ...

## Claim-to-Experiment Map
| Claim | Why it matters | Experiment | Metric | Success condition | Failure condition |
|---|---|---|---|---|---|
| ... | ... | ... | ... | ... | ... |

## Baselines
- Standard baseline: ...
- Simplest credible baseline: ...
- Closest prior-work baseline: ...
- Reviewer-demanded baseline: ...

## Tier 1: Must-Run Experiments
1. ...
   - Purpose: ...
   - Dataset / benchmark: ...
   - Baselines: ...
   - Metrics: ...
   - Why this is mandatory: ...

## Tier 2: High-Leverage Experiments
1. ...
   - Purpose: ...
   - Dataset / benchmark: ...
   - Baselines: ...
   - Metrics: ...
   - Acceptance impact: ...

## Tier 3: Stretch Experiments
1. ...
   - Purpose: ...
   - Trigger to run: ...

## Ablations
- Component isolation: ...
- Sensitivity variables: ...
- Why each ablation matters: ...

## Stress Tests
- Assumption being tested: ...
- Stress regime: ...
- Expected failure pattern: ...

## Execution Order
1. Fastest kill test
2. Core benchmark comparison
3. Ablations
4. Stress tests
5. Stretch experiments

## Publishability Check
- What result is enough for a paper: ...
- What result is only incremental: ...
- What negative result is still scientifically useful: ...

## Implementation Notes
- Data needed: ...
- Compute needed: ...
- Risky dependencies: ...
- What to build first: ...
"""
    write_text(out_path, text.replace("{date}", __import__("datetime").date.today().isoformat()))


def main() -> None:
    ap = argparse.ArgumentParser(description="Scaffold an experiment-plan markdown file.")
    ap.add_argument("topic", help="Topic string for title and filename.")
    ap.add_argument("--venue", default=None, help="Target venue.")
    ap.add_argument("--input", action="append", default=[], help="Relevant upstream artifact path (repeatable).")
    ap.add_argument("--out", default=None, help="Output markdown path.")
    args = ap.parse_args()

    out_path = args.out or artifact_path("experiments", "Experiment-Plan", args.topic)
    scaffold(args.topic, args.venue, list(args.input), out_path)
    print(f"Wrote scaffold to {out_path}")


if __name__ == "__main__":
    main()

